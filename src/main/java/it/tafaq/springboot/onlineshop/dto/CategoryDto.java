package it.tafaq.springboot.onlineshop.dto;

public class CategoryDto {
    public String name;
    public Long id;

    public CategoryDto(Long id, String name) {
        this.id = id;
        this.name = name;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }
}
